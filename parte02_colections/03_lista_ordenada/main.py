# Lista de cidades
cidades = ["Goiania", "Cuiabá", "Brasília", "Florianópolis", "Lucas do Rio Verde"]

# ordenar a lista
cidades.sort()

# exibe a lista em ordem alfabética
for cidade in cidades:
    print(cidade)

# reverte a lista
cidades.sort(reverse=True)

# exibe a lista em ordem reversa
for cidade in cidades:
    print(cidade)